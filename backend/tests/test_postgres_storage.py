@pytest.mark.parametrize("mode", ["disable", "prefer", "require", "verify-ca", "verify-full"])
def test_remote_connections_never_downgrade_tls_verification(monkeypatch, mode):
    psycopg = pytest.importorskip("psycopg")
    observed = []

    def no_connection(*args, **kwargs):
        observed.append(kwargs)
        raise RuntimeError("DO_NOT_LOG_PROVIDER_CONNECTION_DETAILS")

    monkeypatch.setattr(psycopg, "connect", no_connection)
    try:
        with pytest.raises(sqlite3.OperationalError) as caught:
            connect_postgres(f"postgresql://unused.invalid/test?sslmode={mode}", timeout=0.1)
        assert observed[0]["sslmode"] == "verify-full"
        assert "DO_NOT_LOG" not in str(caught.value)
    finally:
        close_postgres_pools()


