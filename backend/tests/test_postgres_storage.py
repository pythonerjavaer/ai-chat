def test_pg_literals_null_dates_unicode_and_sql_injection_are_values(pg):
    connect, _, _ = pg
    with connect() as connection:
        connection.ensure_schema()
        row = connection.execute("SELECT '?' AS question, '100%' AS percent, ? AS value", ("'; DROP SCHEMA x; % ?",)).fetchone()
        assert tuple(row) == ("?", "100%", "'; DROP SCHEMA x; % ?")
        row = connection.execute(
            "SELECT DATE('now') AS day, datetime('now') AS instant, "
            "julianday(?) AS first, julianday(?) AS same, julianday(?) AS invalid, "
            "json_extract(?, '$.verification_status') AS status",
            ("2026-08-30T01:00:00+01:00", "2026-08-30T00:00:00Z", "invalid-date",
             '{"verification_status":"pending"}'),
        ).fetchone()
        assert row["day"] == datetime.now(timezone.utc).date().isoformat()
        assert row["first"] == row["same"]
        assert row["invalid"] is None
        assert row["status"] == "pending"
        assert connection.execute("SELECT ? LIKE ?", ("AbC招聘", "%aBc%")).fetchone()[0] is True
        assert connection.execute("SELECT ? LIKE ?", ("Ä", "ä")).fetchone()[0] is False
        with sqlite3.connect(":memory:") as reference:
            for value, pattern in ((r"a\b", r"a\b"), (r"a\_b", r"a\_b"), ("a_b", r"a\_b")):
                expected = reference.execute("SELECT ? LIKE ?", (value, pattern)).fetchone()[0]
                actual = connection.execute("SELECT ? LIKE ?", (value, pattern)).fetchone()[0]
                assert actual == bool(expected)


def test_pg_pragma_identity_deferrable_and_large_numeric_roundtrip(pg):
    connect, dsn, schema = pg
    with connect() as connection:
        connection.executescript("""
            CREATE TABLE parent(id INTEGER PRIMARY KEY AUTOINCREMENT, name TEXT);
            CREATE TABLE child(id INTEGER PRIMARY KEY, parent_id INTEGER, score REAL,
                FOREIGN KEY(parent_id) REFERENCES parent(id) ON DELETE CASCADE);
        """)
        columns = {row["name"]: dict(row) for row in connection.execute("PRAGMA table_info(child)").fetchall()}
        assert columns["id"]["pk"] == 1
        assert columns["parent_id"]["type"] == "bigint"
        assert columns["score"]["type"] == "double precision"
        connection.execute("SET CONSTRAINTS ALL DEFERRED")
        connection.execute("INSERT INTO child VALUES (?, ?, ?)", (2**50, 2**40, 0.1234567890123456))
        connection.execute("INSERT INTO parent(id,name) VALUES (?, ?)", (2**40, "parent"))
    with connect() as connection:
        row = connection.execute("SELECT id,score FROM child").fetchone()
        assert row[0] == 2**50
        assert row[1] == 0.1234567890123456
        connection.execute("DELETE FROM parent WHERE id=?", (2**40,))
        assert connection.execute("SELECT COUNT(*) FROM child").fetchone()[0] == 0
    import psycopg
    with psycopg.connect(dsn) as connection:
        row = connection.execute(
            "SELECT condeferrable, condeferred FROM pg_constraint c "
            "JOIN pg_namespace n ON n.oid=c.connamespace WHERE n.nspname=%s AND contype='f'",
            (schema,),
        ).fetchone()
        assert row == (True, False)


def test_pg_executemany_rowcount_explicit_returning_and_ignore(pg):
    connect, _, _ = pg
    with connect() as connection:
        connection.execute("CREATE TABLE radar_events(id INTEGER PRIMARY KEY AUTOINCREMENT, event_key TEXT UNIQUE)")
        cursor = connection.executemany("INSERT INTO radar_events(event_key) VALUES (?)", [("a",), ("b",)])
        assert cursor.rowcount == 2
        assert cursor.lastrowid is None
        ignored = connection.execute("INSERT OR IGNORE INTO radar_events(event_key) VALUES (?)", ("a",))
        assert ignored.rowcount == 0
        assert ignored.lastrowid is None
        explicit = connection.execute(
            "INSERT INTO radar_events(event_key) VALUES (?) RETURNING id,event_key", ("c",)
        )
        assert explicit.fetchone()["event_key"] == "c"
        changed = connection.execute("UPDATE radar_events SET event_key=? WHERE event_key=?", ("d", "b"))
        assert changed.rowcount == 1


def test_pg_pool_is_bounded_and_context_returns_connection(pg):
    connect, _, _ = pg
    first = connect(max_size=1)
    try:
        with pytest.raises(sqlite3.OperationalError, match="busy"):
            connect(max_size=1, timeout=0.03)
    finally:
        first.close()
    with connect(max_size=1, timeout=1) as connection:
        assert connection.execute("SELECT 1").fetchone()[0] == 1
    with pytest.raises(sqlite3.ProgrammingError, match="closed"):
        connection.execute("SELECT 1")


def test_pg_private_schema_and_new_objects_have_no_public_privileges(pg):
    connect, dsn, schema = pg
    with connect() as connection:
        connection.execute("CREATE TABLE private_rows(id INTEGER PRIMARY KEY AUTOINCREMENT, value TEXT)")
    import psycopg
    with psycopg.connect(dsn) as connection:
        public_schema_grants = connection.execute(
            "SELECT COUNT(*) FROM pg_namespace n, "
            "LATERAL aclexplode(COALESCE(n.nspacl,acldefault('n',n.nspowner))) a "
            "WHERE n.nspname=%s AND a.grantee=0", (schema,),
        ).fetchone()[0]
        assert public_schema_grants == 0
        public_table_grants = connection.execute(
            "SELECT COUNT(*) FROM pg_class c JOIN pg_namespace n ON n.oid=c.relnamespace, "
            "LATERAL aclexplode(COALESCE(c.relacl,acldefault('r',c.relowner))) a "
            "WHERE n.nspname=%s AND c.relkind='r' AND a.grantee=0", (schema,),
        ).fetchone()[0]
        assert public_table_grants == 0
