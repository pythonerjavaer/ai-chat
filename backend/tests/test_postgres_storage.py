def test_rows_support_dictionary_indexing_and_value_unpacking():
    row = Row(("id", "label"), (7, "test"))
    assert row["id"] == row["ID"] == row[0] == 7
    assert tuple(row) == (7, "test")
    assert dict(row) == {"id": 7, "label": "test"}
    assert row[:] == (7, "test")
    cursor = Cursor([row, row], names=row.keys(), rowcount=2)
    assert cursor.fetchone() is row
    assert cursor.fetchmany(2) == [row]
    assert cursor.fetchall() == []
    assert cursor.description[0][0] == "id"


def test_provider_error_contains_no_message_or_secret():
    class SensitiveError(Exception):
        sqlstate = "23505"

    error = _safe_error(SensitiveError("password=secret-dsn PRIVATE user payload"))
    assert isinstance(error, sqlite3.IntegrityError)
    assert "23505" in str(error)
    assert "secret" not in str(error)
    assert "PRIVATE" not in str(error)


