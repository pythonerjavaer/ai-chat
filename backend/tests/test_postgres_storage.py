def test_pg_connect_does_not_create_schema_and_rollback_removes_new_schema(pg):
    connect, dsn, schema = pg
    import psycopg
    connection = connect()
    with psycopg.connect(dsn) as observer:
        assert observer.execute("SELECT 1 FROM pg_namespace WHERE nspname=%s", (schema,)).fetchone() is None
    connection.ensure_schema()
    connection.execute("CREATE TABLE entries (id INTEGER PRIMARY KEY AUTOINCREMENT, content TEXT)")
    connection.rollback()
    connection.close()
    with psycopg.connect(dsn) as observer:
        assert observer.execute("SELECT 1 FROM pg_namespace WHERE nspname=%s", (schema,)).fetchone() is None
    with connect() as connection:
        connection.execute("CREATE TABLE entries (id INTEGER PRIMARY KEY AUTOINCREMENT, content TEXT)")
        assert connection.execute("INSERT INTO entries(content) VALUES (?)", ("saved",)).lastrowid == 1


