def test_parameters_are_bound_unchanged_and_never_interpolated():
    untrusted = "'; DROP TABLE users; -- ? % :password"
    plan = compile_sql(
        "SELECT '?' AS q, '100%' AS percentage, ? AS payload -- ? comment\n",
        (untrusted,),
    )
    assert plan.parameters == (untrusted,)
    assert untrusted not in plan.sql
    assert "'?'" in plan.sql
    assert "'100%%'" in plan.sql
    assert plan.sql.count("%s") == 1
    assert untrusted not in repr(plan)


